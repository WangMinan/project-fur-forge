import { expect, test } from '@playwright/test'
import { adminBaseURL, E2E_DATABASE_FILE, loginAsAdmin } from '../e2e/helpers/auth'
import { openFixtureDatabase } from '../e2e/helpers/fixture-db'
import { seedPublicCatalog } from '../e2e/helpers/public-catalog'

test('work navigation uses the shared dialog and preserves cancelled drafts and focus', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  const nativeDialogs: string[] = []
  page.on('dialog', async dialog => { nativeDialogs.push(dialog.type()); await dialog.dismiss() })
  await loginAsAdmin(page)
  await seedPublicCatalog(page, [{ slug: 'e2e-public-discard', characterName: '离开确认测试', purpose: 'showcase', photos: [{ alt: '测试图片' }] }])
  const sqlite = openFixtureDatabase(E2E_DATABASE_FILE)
  const id = sqlite.prepare("SELECT id FROM works WHERE slug='e2e-public-discard'").pluck().get() as string
  sqlite.close()
  await page.goto(`${adminBaseURL}/admin/works`)
  await page.locator(`a[href="/admin/works/${id}"]`).first().click()
  const species = page.getByLabel('物种', { exact: false })
  await species.fill('犬科-已保存')
  await page.getByRole('button', { name: '保存修改', exact: true }).click()
  await expect(page.getByRole('button', { name: '保存修改', exact: true })).toBeDisabled()
  await species.fill('未保存的物种')
  const destination = page.getByRole('link', { name: '← 作品', exact: true })
  await destination.click()
  const dialog = page.getByRole('dialog', { name: '放弃未保存的修改？' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('button', { name: '继续编辑' })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: '放弃修改并离开' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(destination).toBeFocused()
  await expect(species).toHaveValue('未保存的物种')
  await expect(page).toHaveURL(new RegExp(`/admin/works/${id}$`))
  // Router back navigation must await the same decision, without discarding the edit.
  await page.goBack()
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: '继续编辑' }).click()
  await expect(species).toHaveValue('未保存的物种')
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 900 })
    await page.locator('a[href="/admin/works"]').filter({ hasText: '作品' }).last().click()
    await expect(dialog).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`discard-${width}.png`) })
    await dialog.getByRole('button', { name: '继续编辑' }).click()
  }
  const unloadPrevented = await page.evaluate(() => !window.dispatchEvent(new Event('beforeunload', { cancelable: true })))
  expect(unloadPrevented).toBe(true)
  await page.getByRole('button', { name: '保存修改', exact: true }).click()
  await expect(page.getByRole('button', { name: '保存修改', exact: true })).toBeDisabled()
  await page.locator('a[href="/admin/works"]').filter({ hasText: '作品' }).last().click()
  await expect(page).toHaveURL(/\/admin\/works$/u)
  expect(nativeDialogs).toEqual([])
})

test('site copy language and page changes use the same discard component', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  const nativeDialogs: string[] = []
  page.on('dialog', async dialog => { nativeDialogs.push(dialog.type()); await dialog.dismiss() })
  await loginAsAdmin(page)
  await page.goto(`${adminBaseURL}/admin/works`)
  await page.getByRole('link', { name: '站点配置', exact: true }).click()
  const language = page.getByRole('group', { name: '编辑语言' })
  const input = page.locator('[data-section="about"]').getByLabel('工作室介绍', { exact: true })
  await input.fill('不能丢失的中文草稿')
  const english = language.getByRole('button', { name: 'English', exact: true })
  await english.click()
  const switchDialog = page.getByRole('dialog', { name: '放弃修改并切换语言？' })
  await expect(switchDialog).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('dialog')).toHaveCount(1)
  await expect(switchDialog).toBeVisible()
  await expect(page).toHaveURL(/\/admin\/site\/content$/u)
  await switchDialog.getByRole('button', { name: '继续编辑' }).click()
  await expect(input).toHaveValue('不能丢失的中文草稿')
  await expect(english).toBeFocused()
  await english.click()
  await switchDialog.getByRole('button', { name: '放弃修改并切换' }).click()
  await expect(english).toHaveAttribute('aria-pressed', 'true')
  await expect(input).not.toHaveValue('不能丢失的中文草稿')
  await input.fill('Unsaved English draft')
  await page.getByRole('link', { name: '委托申请', exact: true }).click()
  const leaveDialog = page.getByRole('dialog', { name: '放弃未保存的修改？' })
  await leaveDialog.getByRole('button', { name: '继续编辑' }).click()
  await expect(input).toHaveValue('Unsaved English draft')
  await page.getByRole('link', { name: '委托申请', exact: true }).click()
  await leaveDialog.getByRole('button', { name: '放弃修改并离开' }).click()
  await expect(page).toHaveURL(/\/admin\/commissions$/u)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.style.overflow)).not.toBe('hidden')
  expect(nativeDialogs).toEqual([])
})
